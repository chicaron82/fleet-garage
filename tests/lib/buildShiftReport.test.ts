import { describe, it, expect } from 'vitest';
import {
  fmtMinutes,
  formatDateStr,
  deriveShiftLine,
  buildReport,
  reportOthBreakdown,
  type ReportData,
  type ReportThroughput,
} from '../../src/lib/buildShiftReport';
