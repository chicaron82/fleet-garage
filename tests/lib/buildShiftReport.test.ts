// ── small helpers ─────────────────────────────────────────────────────────────

describe('fmtMinutes', () => {
  it('formats minutes, whole hours, and mixed', () => {
    expect(fmtMinutes(45)).toBe('45m');
    expect(fmtMinutes(60)).toBe('1h');
    expect(fmtMinutes(125)).toBe('2h 5m');
  });

  it('rounds float artifacts instead of rendering "51.99999999999994m"', () => {
    expect(fmtMinutes(411.99999999999994)).toBe('6h 52m');
  });
});

describe('formatDateStr', () => {
  it('builds a long local date from a YYYY-MM-DD string', () => {
    const s = formatDateStr('2026-05-22'); // a Friday
    expect(s).toMatch(/Friday/);
    expect(s).toMatch(/May/);
    expect(s).toMatch(/22/);
    expect(s).toMatch(/2026/);
  });
});

describe('deriveShiftLine', () => {
  function shift(over: Partial<ShiftWithUser>): ShiftWithUser {
    return {
      id: 's1', userId: 'u1', date: '2026-05-22', shiftType: 'closing',
      createdAt: '', updatedAt: '', branchId: 'YWG', user: { name: 'Ana', role: 'VSA' },
      ...over,
    };
  }

  it('defaults when no shift on that day', () => {
    expect(deriveShiftLine([], 'u1', '2026-05-22')).toBe('8-hour shift');
  });

  it('renders label + time range (en-dash)', () => {
    const line = deriveShiftLine([shift({ startTime: '13:30', endTime: '22:00' })], 'u1', '2026-05-22');
    expect(line).toBe('Closing shift 13:30–22:00');
  });

  it('renders label only when no times', () => {
    expect(deriveShiftLine([shift({ shiftType: 'pto' })], 'u1', '2026-05-22')).toBe('PTO');
  });
});

